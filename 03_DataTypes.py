a = 54
print(type(a)) #This will print <class 'int'> because the variable 'a' is an integer.

b = 3.14
print(type(b)) #This will print <class 'float'> because the variable 'b' is a floating-point number.

c = "Hello, World!"
print(type(c)) #This will print <class 'str'> because the variable 'c' is a string.

d = True
print(type(d)) #This will print <class 'bool'> because the variable 'd' is a boolean.

e = [1, 2, 3, 4, 5]
print(type(e)) #This will print <class 'list'> because the variable 'e' is a list.  

f = (1, 2, 3, 4, 5)
print(type(f)) #This will print <class 'tuple'> because the variable 'f' is a tuple.  

g = {1, 2, 3, 4, 5}
print(type(g)) #This will print <class 'set'> because the variable 'g' is a set.  

h = {"name": "John", "age": 30}
print(type(h)) #This will print <class 'dict'> because the variable 'h' is a dictionary.  

i = None
print(type(i)) #This will print <class 'NoneType'> because the variable 'i' is None.

j = 32j
print(type(j)) #This will print <class 'complex'> because the variable 'j' is a complex number.